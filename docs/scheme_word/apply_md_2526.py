def apply(path: Path, replaces, deletes, inserts, label: str):
    text = path.read_text(encoding="utf-8")
    errors = []
    for old, new, expect in replaces:
        n = text.count(old)
        if n != expect:
            errors.append(f"[{label}] 替换计数({n}!={expect}): {old[:46]}")
            continue
        text = text.replace(old, new)
    for old, expect in deletes:
        n = text.count(old)
        if n != expect:
            errors.append(f"[{label}] 删除计数({n}!={expect}): {old[:46]}")
            continue
        text = text.replace(old, "")
    for item in inserts:
        if len(item) == 2:
            anchor, lines, expect = item[0], item[1], 1
        else:
            anchor, lines, expect = item
        n = text.count(anchor)
        if n != expect:
            errors.append(f"[{label}] 插入锚点计数({n}!={expect}): {anchor[:46]}")
            continue
        if lines:
            text = text.replace(anchor, anchor + "\n" + "\n".join(lines))
    if errors:
        print(f"!! {label} 中止，未写回：")
        for e in errors:
            print("  ", e)
        return False
    path.write_text(text, encoding="utf-8")
    print(f"{label} 校准完成")
    return True


